import type { TourProject } from '../types/project';
import type { ArchiveProgress, ExternalDependency } from './portableProjectArchive';
import { exportProjectArchive } from './portableProjectArchive';

export interface ProductionBundleResult {
  fileCount: number;
  totalBytes: number;
  externalDependencies: ExternalDependency[];
}

function slugify(value: string): string {
  return value.toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || '360-studio-tour';
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character] ?? character);
}

async function readPlayerRuntime(filename: 'tour-player.js' | 'tour-player.css'): Promise<Blob> {
  const url = new URL(`player-runtime/${filename}`, document.baseURI);
  let response: Response;
  try {
    response = await fetch(url, { cache: 'no-cache' });
  } catch {
    throw new Error(`Could not reach ${filename}. Restart the Studio with npm run dev, or build the Studio with npm run build first. The player runtime is generated by the build pipeline.`);
  }
  if (!response.ok) {
    throw new Error(`The standalone player runtime is missing (${url.pathname}, HTTP ${response.status}). Run npm run build:player, then reload the Studio.`);
  }
  return new Blob([await response.arrayBuffer()], { type: filename.endsWith('.js') ? 'text/javascript' : 'text/css' });
}

function deploymentGuide(project: TourProject): string {
  return `360 Studio production tour deployment\n=======================================\n\nTour: ${project.name}\n\nCONTENTS\n- index.html: standalone tour entry page\n- tour-player.js / tour-player.css: bundled viewer runtime (does not load the Studio editor)\n- project.json: tour configuration\n- archive-manifest.json: map of asset IDs to files bundled into this build\n- assets/: uploaded images, video, audio and other included project assets\n- tours/: included tiled panorama previews, originals (when available) and tiles\n\nDEPLOY TO NGINX\n1. Extract this ZIP into a dedicated directory, for example /var/www/360-tours/${slugify(project.name)}.\n2. Configure Nginx to serve index.html from that directory over HTTPS.\n3. Ensure JSON files use application/json and media files use their proper content types.\n4. Do not change the relative directory structure. Asset paths are relative to index.html so the tour can live under a subdirectory.\n5. Open the URL ending in /index.html or the directory URL and test every scene and hotspot.\n\nExample Nginx location (adjust root/path to your server):\n  location /tours/${slugify(project.name)}/ {\n      try_files $uri $uri/ =404;\n      add_header X-Content-Type-Options nosniff;\n  }\n\nCACHE NOTES\n- Keep index.html, project.json and archive-manifest.json revalidatable (Cache-Control: no-cache) when replacing a tour build.\n- For a long-lived cache, deploy each build to a new versioned directory rather than overwriting files with the same names.\n- Preserve byte ranges for large video files so seeking stays responsive.\n\nLIMITATIONS\n- ZIP64 is not supported; project archives over the classic 4 GiB ZIP limit are rejected.\n- External URLs that browser CORS or authentication prevents from downloading remain linked in the project and are listed in archive-manifest.json. They must stay available to visitors.\n- Audio playback follows browser autoplay rules. Visitors may need to enable sound once.\n- The standalone bundle does not contain Studio editing capabilities. To change the tour, edit the project in Studio and build a new bundle.\n`;
}

function standaloneHtml(projectName: string): string {
  return `<!doctype html>\n<html lang="en">\n<head>\n  <meta charset="UTF-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n  <meta name="theme-color" content="#080b10">\n  <meta name="description" content="Interactive 360-degree virtual event experience">\n  <title>${escapeHtml(projectName)}</title>\n  <link rel="stylesheet" href="./tour-player.css">\n</head>\n<body>\n  <div id="tour-root"><main class="tour-boot-error"><div class="tour-boot-error-mark">360</div><h1>Loading your experience…</h1><p>Preparing panoramas and interactive scenes.</p></main></div>\n  <script defer src="./tour-player.js"></script>\n</body>\n</html>\n`;
}

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.style.display = 'none';
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 30_000);
}

/** Bundle project media and configuration with the prebuilt standalone player runtime. */
export async function exportProductionTourBundle(
  project: TourProject,
  onProgress?: (value: ArchiveProgress) => void,
): Promise<ProductionBundleResult> {
  const [runtimeJs, runtimeCss] = await Promise.all([
    readPlayerRuntime('tour-player.js'),
    readPlayerRuntime('tour-player.css'),
  ]);
  const filename = `${slugify(project.name)}-production.zip`;
  const result = await exportProjectArchive(project, onProgress, {
    download: false,
    filename,
    extraEntries: [
      { path: 'index.html', blob: new Blob([standaloneHtml(project.name)], { type: 'text/html;charset=utf-8' }) },
      { path: 'tour-player.js', blob: runtimeJs },
      { path: 'tour-player.css', blob: runtimeCss },
      { path: 'DEPLOYMENT.txt', blob: new Blob([deploymentGuide(project)], { type: 'text/plain;charset=utf-8' }) },
    ],
  });
  triggerDownload(result.blob, filename);
  return { fileCount: result.fileCount, totalBytes: result.totalBytes, externalDependencies: result.externalDependencies };
}
