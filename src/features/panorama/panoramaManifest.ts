import type { TiledPanoramaLevel, TiledPanoramaSource } from '../../types/project';

export interface TiledPanoramaManifest {
  schemaVersion: 1;
  baseUrl?: string;
  tileUrlTemplate: string;
  levels: TiledPanoramaLevel[];
  source?: { width?: number; height?: number; originalFileName?: string; originalUrl?: string };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isPowerOfTwo(value: number): boolean {
  return Number.isInteger(value) && value > 0 && (value & (value - 1)) === 0;
}

function validateLevel(value: unknown, index: number): TiledPanoramaLevel {
  if (!isRecord(value)) throw new Error(`Tile level ${index + 1} is not an object.`);
  const { width, cols, rows, zoomRange } = value;
  if (typeof width !== 'number' || !Number.isFinite(width) || width < 1) {
    throw new Error(`Tile level ${index + 1} has an invalid width.`);
  }
  if (typeof cols !== 'number' || !isPowerOfTwo(cols) || cols < 4 || cols > 64) {
    throw new Error(`Tile level ${index + 1} must use 4, 8, 16, 32, or 64 columns.`);
  }
  if (typeof rows !== 'number' || !isPowerOfTwo(rows) || rows < 2 || rows > 32 || rows * 2 !== cols) {
    throw new Error(`Tile level ${index + 1} rows must be half the column count (2, 4, 8, 16, or 32).`);
  }
  if (!Array.isArray(zoomRange) || zoomRange.length !== 2 || typeof zoomRange[0] !== 'number' || typeof zoomRange[1] !== 'number' || zoomRange[0] < 0 || zoomRange[1] > 100 || zoomRange[0] >= zoomRange[1]) {
    throw new Error(`Tile level ${index + 1} has an invalid zoomRange.`);
  }
  return { width, cols, rows, zoomRange: [zoomRange[0], zoomRange[1]] };
}

/** Fetch and validate a manifest generated by scripts/prepare-panorama.mjs.
 * The manifest and its assets must be served over HTTP(S) with CORS enabled if cross-origin.
 */
export async function loadTiledPanoramaManifest(manifestUrlInput: string): Promise<TiledPanoramaSource> {
  const manifestUrl = new URL(manifestUrlInput.trim()).href;
  if (!['http:', 'https:'].includes(new URL(manifestUrl).protocol)) {
    throw new Error('Tiled panorama manifests must use an HTTP or HTTPS URL.');
  }
  const response = await fetch(manifestUrl, { cache: 'no-cache' });
  if (!response.ok) throw new Error(`Could not load tile manifest (HTTP ${response.status}).`);
  const raw: unknown = await response.json();
  if (!isRecord(raw) || raw.schemaVersion !== 1 || typeof raw.tileUrlTemplate !== 'string' || !raw.tileUrlTemplate.trim()) {
    throw new Error('Invalid tile manifest. Expected schemaVersion 1 and tileUrlTemplate.');
  }
  if (!raw.tileUrlTemplate.includes('{col}') || !raw.tileUrlTemplate.includes('{row}') || !(raw.tileUrlTemplate.includes('{width}') || raw.tileUrlTemplate.includes('{level}'))) {
    throw new Error('The tile URL template must include {col}, {row}, and either {width} or {level}.');
  }
  if (!Array.isArray(raw.levels) || raw.levels.length < 1 || raw.levels.length > 8) {
    throw new Error('The tile manifest must contain between 1 and 8 resolution levels.');
  }
  const levels = raw.levels.map(validateLevel);
  for (let i = 1; i < levels.length; i += 1) {
    if (levels[i].width <= levels[i - 1].width) throw new Error('Tile levels must be sorted from lowest to highest width.');
  }
  const baseUrl = typeof raw.baseUrl === 'string' && raw.baseUrl.trim()
    ? new URL(raw.baseUrl, manifestUrl).href
    : undefined;
  if (baseUrl && !['http:', 'https:'].includes(new URL(baseUrl).protocol)) {
    throw new Error('The preview URL must use HTTP or HTTPS.');
  }
  // Protect tokens while URL resolves relative paths, then put the template tokens back.
  const protectedTemplate = raw.tileUrlTemplate
    .replaceAll('{width}', '__PANO_WIDTH__')
    .replaceAll('{level}', '__PANO_LEVEL__')
    .replaceAll('{col}', '__PANO_COL__')
    .replaceAll('{row}', '__PANO_ROW__');
  const resolvedTemplateUrl = new URL(protectedTemplate, manifestUrl);
  if (!['http:', 'https:'].includes(resolvedTemplateUrl.protocol)) {
    throw new Error('Tile URLs must use HTTP or HTTPS.');
  }
  const resolvedTemplate = resolvedTemplateUrl.href
    .replaceAll('__PANO_WIDTH__', '{width}')
    .replaceAll('__PANO_LEVEL__', '{level}')
    .replaceAll('__PANO_COL__', '{col}')
    .replaceAll('__PANO_ROW__', '{row}');
  const source = isRecord(raw.source) ? raw.source : {};
  return {
    manifestUrl,
    baseUrl,
    tileUrlTemplate: resolvedTemplate,
    levels,
    ...(typeof source.width === 'number' ? { sourceWidth: source.width } : {}),
    ...(typeof source.height === 'number' ? { sourceHeight: source.height } : {}),
    ...(typeof source.originalUrl === 'string' ? { originalUrl: new URL(source.originalUrl, manifestUrl).href } : {}),
  };
}
